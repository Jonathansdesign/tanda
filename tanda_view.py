"""Turns tool results into things a person can read.

No Streamlit in this file: just plain functions that take dictionaries and
return rows of text. That keeps the web page (app.py) thin and lets us test
this logic without a browser.
"""

HOW_TO_READ = """\
**Predicted on-time**: our best estimate of the chance a member pays on time next \
month, worked out from their payment history with Bayes' theorem.

**90% interval**: a range that likely contains the member's true on-time probability. \
A wide range means little data, so we are not sure.

**Watch**: the member was already paid out and their predicted on-time probability is \
below 0.75. The 0.75 cutoff is a choice made for this demo, not a statistical result.

**Expected loss**: the average dollars the group would lose from missed payments after \
payout, if the circle used this payout order.

**Chance of 3+ missed payments**: the probability that at least three payments are \
missed by members who have already been paid.

**Simulated**: these members' payment histories are generated by the computer, not real \
people. PayPal calls go to the sandbox, so no real money moves.
"""


def md(text):
    """Escape dollar signs so Streamlit shows them as money, not as math.

    Streamlit's text functions read $...$ as a formula. A backslash before each $
    makes it an ordinary dollar sign.
    """
    return text.replace("$", "\\$")


def status_rows(status):
    """One row per member, with friendly column names, for the status table."""
    rows = []
    for m in status["members"]:
        lo, hi = m["interval_90"]
        rows.append({
            "Member": m["name"],
            "Paid out yet?": "yes" if m["already_paid"] else "no",
            "Months of history": m["months_of_history"],
            "Predicted on-time": m["predicted_on_time"],
            "90% interval": f"{lo:.2f} to {hi:.2f}",
            "Watch": "watch" if m["needs_attention"] else "",
            "Account": "saved wallet" if m["has_paypal_wallet"] else "simulated",
        })
    return rows


def ledger_rows(ledger):
    """One row per finished round."""
    return [{
        "Round": r["round"],
        "Winner": r["winner"],
        "Pot collected": f"${r['pot']:.2f}",
        "Missed after payout": ", ".join(r["missed_by_paid_members"]) or "none",
        "Payout": r["payout"],
    } for r in ledger]


def order_text(order):
    return " -> ".join(order)


def risk_sentences(score):
    """Two plain-English lines comparing the best order with a random one."""
    return [
        f"Expected loss: ${score['expected_loss']:.2f} with this order, versus "
        f"${score['random_order_expected_loss']:.2f} for a random order.",
        f"Chance of {score['bad_outcome_means']}: {score['chance_of_bad_outcome']:.1%} "
        f"with this order, versus {score['random_order_chance_of_bad_outcome']:.1%} "
        f"for a random order.",
    ]


def proposal_lines(p):
    """Plain-English description of a proposal waiting for approval."""
    real = p["will_charge_real_paypal_wallets"]
    lines = [
        f"Round {p['round']}: the pot goes to {p['winner']}.",
        f"Each member contributes ${p['contribution_each']:.2f} "
        f"(pot of up to ${p['maximum_pot']:.2f}).",
    ]
    if real:
        lines.append("Real PayPal sandbox wallet(s) will be charged: " + ", ".join(real) + ".")
    else:
        lines.append("No real PayPal wallets are involved, so this round is fully simulated.")
    return lines